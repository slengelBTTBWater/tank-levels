// Fetches the latest level for each tank in tanks.json from the Zonelog API
// and writes tank-data.js for the public page.
//
// Needs these environment variables (stored as GitHub secrets, never in the repo):
//   ZONELOG_CLIENT_ID, ZONELOG_CLIENT_SECRET, ZONELOG_COMPANY_GUID
//
// Run: node scripts/update-tanks.mjs   (Node 20 or newer)

import { readFile, writeFile } from "node:fs/promises";

const TOKEN_URL = "https://zonelogidentity.net/connect/token";
const API = "https://api.zonelog.net/api/waternet";
const LOOKBACK_HOURS = 48;
const CONFIG = new URL("../tanks.json", import.meta.url);
const OUT = new URL("../tank-data.js", import.meta.url);
const PREFIX = "window.TANK_DATA = ";

function env(name) {
  const value = process.env[name];
  if (!value) throw new Error(`Missing environment variable ${name}`);
  return value;
}

async function getToken() {
  const res = await fetch(TOKEN_URL, {
    method: "POST",
    headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({
      grant_type: "client_credentials",
      client_id: env("ZONELOG_CLIENT_ID"),
      client_secret: env("ZONELOG_CLIENT_SECRET"),
      scope: "AG_DatabaseAPI",
    }),
  });
  if (!res.ok) throw new Error(`Token request failed: ${res.status} ${await res.text()}`);
  return (await res.json()).access_token;
}

// Zonelog date parameters, in UTC, e.g. 2026-10-26T14:00:00
const apiDate = d => d.toISOString().slice(0, 19);

// readingDateUTC may come back without a time zone suffix; it is always UTC.
const parseUtc = s => new Date(/[zZ]|[+-]\d\d:?\d\d$/.test(s) ? s : s + "Z");

// Tank level in feet of water. The loggers report ftH2O, but convert in case
// the account's display units are ever changed.
function toFeet(value, units) {
  const u = (units || "").toLowerCase();
  if (u.includes("psi")) return value * 2.3067;
  if (u.includes("bar")) return value * 33.4553;
  if (u.startsWith("m")) return value * 3.28084;
  return value;
}

async function latestReading(token, serial) {
  const now = new Date();
  const params = new URLSearchParams({
    companyGuid: env("ZONELOG_COMPANY_GUID"),
    serial,
    startDate: apiDate(new Date(now - LOOKBACK_HOURS * 36e5)),
    endDate: apiDate(now),
  });
  const res = await fetch(`${API}/pressure?${params}`, { headers: { Authorization: `Bearer ${token}` } });
  if (!res.ok) throw new Error(`Pressure request for logger ${serial} failed: ${res.status} ${await res.text()}`);

  const rows = (await res.json()).filter(r => r.data != null && String(r.serial) === serial);
  if (!rows.length) throw new Error(`No pressure readings for logger ${serial} in the last ${LOOKBACK_HOURS} hours`);

  const latest = rows.reduce((a, b) => (parseUtc(b.readingDateUTC) > parseUtc(a.readingDateUTC) ? b : a));
  console.log(`Logger ${serial}: ${rows.length} readings; latest ${latest.data} ${latest.units} ` +
    `(channel ${latest.channelLetter}) at ${latest.readingDateUTC}`);
  return {
    level_ft: Math.round(toFeet(latest.data, latest.units) * 10) / 10,
    reading_time: parseUtc(latest.readingDateUTC).toISOString(),
  };
}

// Last published readings, so a tank keeps its previous value if one fetch fails.
async function previousReadings() {
  try {
    const text = await readFile(OUT, "utf8");
    const json = text.slice(text.indexOf(PREFIX) + PREFIX.length).trim().replace(/;$/, "");
    return Object.fromEntries(JSON.parse(json).tanks.map(t => [t.serial, t]));
  } catch {
    return {};
  }
}

const config = JSON.parse(await readFile(CONFIG, "utf8"));
const previous = await previousReadings();
const token = await getToken();
let failures = 0;

const tanks = [];
for (const t of config.tanks) {
  const tank = { ...t };
  if (!t.installing) {
    try {
      Object.assign(tank, await latestReading(token, t.serial));
    } catch (err) {
      failures++;
      console.error(err.message);
      const old = previous[t.serial];
      if (old?.level_ft != null) Object.assign(tank, { level_ft: old.level_ft, reading_time: old.reading_time });
    }
  }
  tanks.push(tank);
}

const data = { sample: false, updated: new Date().toISOString(), notice: config.notice || "", tanks };
await writeFile(OUT,
  "// Generated by scripts/update-tanks.mjs — edit tanks.json instead.\n" +
  PREFIX + JSON.stringify(data, null, 2) + ";\n");
console.log(`Wrote tank-data.js (${tanks.length} tanks, ${failures} failed)`);
if (failures) process.exitCode = 1;
